"""Направление зависимостей — падающий тест, а не картинка в README.

Разбор идёт по дереву импортов (`ast`), а не поиском подстроки: строка
"from cli" встречается в комментарии и в докстринге, и подстрочная проверка
краснела бы на честном тексте.
"""

from __future__ import annotations

import ast
from pathlib import Path

ПАКЕТ = Path(__file__).resolve().parents[2] / "src" / "tutu_search_flights"

# Слой -> слои, которые ему запрещено импортировать.
ЗАПРЕТЫ = {
    "core": ("mcp", "cli"),
    "mcp": ("cli",),
    "cli": (),
}


def импорты(модуль: Path) -> list[str]:
    дерево = ast.parse(модуль.read_text(encoding="utf-8"), filename=str(модуль))
    имена: list[str] = []
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            имена += [псевдоним.name for псевдоним in узел.names]
        elif isinstance(узел, ast.ImportFrom):
            # level > 0 — относительный импорт; для него имя слоя даёт сам путь файла
            имена.append(узел.module or "")
    return имена


def слой(имя_импорта: str, модуль: Path) -> str | None:
    """Слой, на который указывает импорт, или None если это не наш пакет."""
    части = имя_импорта.split(".")
    if части[:1] == ["tutu_search_flights"] and len(части) > 1:
        return части[1]
    if имя_импорта in ЗАПРЕТЫ:  # относительный импорт внутри пакета
        return имя_импорта
    return None


def test_слои_не_тянутся_вверх() -> None:
    нарушения: list[str] = []

    for свой_слой, запрещено in ЗАПРЕТЫ.items():
        папка = ПАКЕТ / свой_слой
        for модуль in sorted(папка.rglob("*.py")):
            for имя in импорты(модуль):
                цель = слой(имя, модуль)
                if цель in запрещено:
                    нарушения.append(f"{свой_слой}/{модуль.name} импортирует {цель} ({имя})")

    assert not нарушения, "зависимости направлены вверх — " + "; ".join(нарушения)


def test_все_три_слоя_на_месте() -> None:
    """Тест, который ловит переименование папки раньше, чем это сделает импорт."""
    отсутствуют = [имя for имя in ЗАПРЕТЫ if not (ПАКЕТ / имя).is_dir()]

    assert not отсутствуют, f"нет слоёв: {', '.join(отсутствуют)}"
